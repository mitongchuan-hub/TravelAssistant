import { describe, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import IdeaBoard from '@/components/IdeaBoard.vue'
import { deferred } from './fixtures'

const setup = (text = '', revision = 3) => {
  const saveRequirements = vi.fn<(text: string, revision: number) => Promise<boolean>>().mockResolvedValue(true)
  const wrapper = mount(IdeaBoard, { props: { text, revision, destination: '杭州', city: true, busy: false, feedback: '', generationWarning: '', saveRequirements }, global: { stubs: { RouterLink: true } } })
  return { wrapper, saveRequirements }
}

async function editBody(wrapper: ReturnType<typeof setup>['wrapper']) {
  if (!wrapper.find('[role="dialog"]').exists()) await wrapper.get('.wall-body-tool').trigger('click')
  await wrapper.get('.requirements-actions button:last-child').trigger('click')
}

describe('single requirements body', () => {
  it('derives every paragraph as a note, exposes full long text and renders safe Markdown in the sheet', async () => {
    const long = '长段'.repeat(100)
    const text = '**慢游**\n\n<script>bad()</script>\n\n![remote](https://evil.invalid/x)\n\n' + Array.from({ length: 9 }, (_, i) => `想法${i}`).join('\n\n') + '\n\n' + long
    const { wrapper } = setup(text)
    expect(wrapper.findAll('.floating-idea')).toHaveLength(13)
    expect(wrapper.find('textarea, [role="dialog"]').exists()).toBe(false)
    expect(wrapper.find('.requirements-body').exists()).toBe(false)
    await wrapper.findAll('.floating-idea').at(-1)!.trigger('click')
    expect(wrapper.get('[role="dialog"]').text()).toContain(long)
    await wrapper.get('.idea-detail-heading button').trigger('click')
    await wrapper.get('.wall-body-tool').trigger('click')
    expect(wrapper.get('[role="dialog"] strong').text()).toBe('慢游')
    expect(wrapper.find('script, img').exists()).toBe(false)
    await wrapper.get('.idea-detail-heading button').trigger('click')
    await wrapper.setProps({ text: '' })
    expect(wrapper.text()).toContain('这里先留给你的旅行想法')
    wrapper.unmount()
  })
  it('captures the original revision, keeps drafts across polls and conflicts, and cancels to the current server body', async () => {
    const { wrapper, saveRequirements } = setup('旧正文')
    await editBody(wrapper)
    await wrapper.get('textarea').setValue('我的草稿')
    await wrapper.setProps({ text: '其他页面的新正文', revision: 4 })
    expect(wrapper.get<HTMLTextAreaElement>('textarea').element.value).toBe('我的草稿')
    expect(wrapper.text()).toContain('不会覆盖新版本')
    saveRequirements.mockResolvedValueOnce(false)
    await wrapper.get('.requirements-editor').trigger('submit'); await flushPromises()
    expect(saveRequirements).toHaveBeenCalledWith('我的草稿', 3)
    expect(wrapper.get<HTMLTextAreaElement>('textarea').element.value).toBe('我的草稿')
    await wrapper.get('.requirements-actions button[type="button"]').trigger('click')
    expect(wrapper.text()).toContain('其他页面的新正文')
    await editBody(wrapper)
    await wrapper.get('textarea').setValue('')
    await wrapper.get('.requirements-editor').trigger('submit'); await flushPromises()
    expect(saveRequirements).toHaveBeenLastCalledWith('', 4)
    expect(wrapper.find('textarea').exists()).toBe(false)
    wrapper.unmount()
  })
  it('quick-add saves the entire latest body once with the click-time revision, including paragraphs beyond eight', async () => {
    const old = Array.from({ length: 12 }, (_, i) => `需求${i}`).join('\n\n') + '\n'
    const { wrapper, saveRequirements } = setup('先前正文')
    await wrapper.get('.wall-quick-add input').setValue('新想法😀')
    await wrapper.setProps({ text: old, revision: 9 })
    const result = deferred<boolean>(); saveRequirements.mockReturnValueOnce(result.promise)
    await wrapper.get('.wall-quick-add').trigger('submit')
    await wrapper.get('.wall-quick-add').trigger('submit')
    expect(saveRequirements).toHaveBeenCalledTimes(1)
    expect(saveRequirements).toHaveBeenCalledWith(old + '\n\n新想法😀', 9)
    result.resolve(true); await flushPromises()
    expect(wrapper.get<HTMLInputElement>('.wall-quick-add input').element.value).toBe('')
    wrapper.unmount()
  })
  it('keeps failed quick-add input on conflict and never automatically rebases or overwrites', async () => {
    const { wrapper, saveRequirements } = setup('旧正文')
    const result = deferred<boolean>(); saveRequirements.mockReturnValueOnce(result.promise)
    await wrapper.get('.wall-quick-add input').setValue('不能丢字😀')
    await wrapper.get('.wall-quick-add').trigger('submit')
    await wrapper.setProps({ text: '并发的新正文', revision: 4 })
    result.resolve(false); await flushPromises()
    expect(saveRequirements).toHaveBeenCalledExactlyOnceWith('旧正文\n\n不能丢字😀', 3)
    expect(wrapper.get<HTMLInputElement>('.wall-quick-add input').element.value).toBe('不能丢字😀')
    expect(wrapper.text()).toContain('不会覆盖其他更新')
    await wrapper.get('.wall-quick-add').trigger('submit'); await flushPromises()
    expect(saveRequirements).toHaveBeenLastCalledWith('并发的新正文\n\n不能丢字😀', 4)
    wrapper.unmount()
  })
  it('keeps over-limit quick-add text without UTF16 truncation or a save', async () => {
    const { wrapper, saveRequirements } = setup('😀'.repeat(19999))
    await wrapper.get('.wall-quick-add input').setValue('😀')
    expect(wrapper.get('input').attributes('maxlength')).toBeUndefined()
    await wrapper.get('.wall-quick-add').trigger('submit'); await flushPromises()
    expect(saveRequirements).not.toHaveBeenCalled()
    expect(wrapper.get<HTMLInputElement>('input').element.value).toBe('😀')
    expect(wrapper.text()).toContain('合并后正文超过')
    wrapper.unmount()
  })
  it('locks submission and cancellation until the save finishes', async () => {
    const { wrapper, saveRequirements } = setup('原文')
    await editBody(wrapper)
    const result = deferred<boolean>(); saveRequirements.mockReturnValueOnce(result.promise)
    await wrapper.get('.requirements-editor').trigger('submit')
    expect(wrapper.get('.requirements-actions button[type="submit"]').attributes('disabled')).toBeDefined()
    expect(wrapper.get('.requirements-actions button[type="button"]').attributes('disabled')).toBeDefined()
    await wrapper.get('.requirements-editor').trigger('submit')
    expect(saveRequirements).toHaveBeenCalledTimes(1)
    result.resolve(false); await flushPromises()
    expect(wrapper.find('textarea').exists()).toBe(true)
    wrapper.unmount()
  })
  it('counts Unicode code points without native UTF16 truncation and rejects growth beyond 20k', async () => {
    const { wrapper, saveRequirements } = setup()
    await editBody(wrapper)
    expect(wrapper.get('textarea').attributes('maxlength')).toBeUndefined()
    const text = '😀'.repeat(20000)
    await wrapper.get('textarea').setValue(text)
    expect(wrapper.text()).toContain('20,000 / 20,000')
    expect(wrapper.get('.requirements-actions button[type="submit"]').attributes('disabled')).toBeUndefined()
    await wrapper.get('textarea').setValue(text + '字')
    await wrapper.get('.requirements-editor').trigger('submit'); await flushPromises()
    expect(saveRequirements).not.toHaveBeenCalled()
    expect(wrapper.get<HTMLTextAreaElement>('textarea').element.value).toBe(text + '字')
    wrapper.unmount()
  })
  it('preserves migrated long text and permits unchanged or shorter saves but not growth', async () => {
    const original = '😀'.repeat(20001)
    const { wrapper, saveRequirements } = setup(original)
    expect(wrapper.text()).toContain('完整内容已保留')
    await editBody(wrapper)
    expect(wrapper.get<HTMLTextAreaElement>('textarea').element.value).toBe(original)
    saveRequirements.mockResolvedValue(false)
    await wrapper.get('.requirements-editor').trigger('submit'); await flushPromises()
    expect(saveRequirements).toHaveBeenCalledWith(original, 3)
    await wrapper.get('textarea').setValue(original + '字')
    expect(wrapper.get('.requirements-actions button[type="submit"]').attributes('disabled')).toBeDefined()
    await wrapper.get('textarea').setValue(original.slice(2))
    expect(wrapper.get('.requirements-actions button[type="submit"]').attributes('disabled')).toBeUndefined()
    wrapper.unmount()
  })
})
