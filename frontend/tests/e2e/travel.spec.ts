  await page.screenshot({ path: `${pictures}/city-outing-form-430.png`, fullPage: true })
  const candidateResponse = page.waitForResponse(response => response.url().endsWith('/api/trips') && response.request().method() === 'POST')
  await submit.click()
  const candidate = await candidateResponse
  expect(candidate.ok()).toBe(true)
  const draft = { lodging_address: '杭州湖滨酒店', transport_mode: 'transit', start_date: '2030-05-01', day_count: '2', revision: '' }
