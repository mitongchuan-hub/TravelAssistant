  await expect(page.getByRole('radio')).toHaveCount(2)
  await expect(page.getByRole('button', { name: '从这里开始', exact: true })).toBeDisabled()
  await expect(page).toHaveURL(/\/trips\/new$/)
  expect(await trips()).toEqual([])
  await noOverflow(page)
  await page.screenshot({ path: `${pictures}/city-outing-candidates-430.png`, fullPage: true })
  await page.getByRole('radio', { name: /湖滨酒店（西湖店）/ }).check()
  const savedResponse = page.waitForResponse(response => response.url().endsWith('/api/trips') && response.request().method() === 'POST')
  await page.getByRole('button', { name: '从这里开始', exact: true }).click()
  const saved = await savedResponse
  expect(saved.ok()).toBe(true)
  expect(Object.keys(saved.request().postDataJSON()).sort()).toEqual(['choice_token', 'poi_id'])
  expect(saved.request().postDataJSON().poi_id).toBe('browser-hotel-0')
  const { trip } = await saved.json()
  expectCurrentTripContract(trip)
  await expect(page).toHaveURL(new RegExp(`/workspace/${trip.id}\\?tab=chat$`))
  const persisted = await trips()
  expect(persisted).toHaveLength(1)
