  await expect(page.locator('input[name="lodging_address"]')).toBeVisible()
  expect(await trips()).toEqual([])
  // Browser constraint validation must keep incomplete/out-of-range drafts local.
  const submit = page.getByRole('button', { name: '创建并开始对话', exact: true })
  await submit.click()
  await expect(page).toHaveURL(/\/trips\/new$/)
  await page.getByLabel('住宿地址或酒店名称', { exact: true }).fill('杭州湖滨酒店')
